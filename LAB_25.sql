ALTER FUNCTION PRINTNUM(@N INT)
RETURNS VARCHAR(500)
AS
BEGIN
DECLARE @I INT , @S VARCHAR(500)
SET @I = 1;
SET @S = ''
WHILE(@I <=@N)
BEGIN
SET @S = @S + CAST(@I AS varchar) + '-'
SET @I = @I+1
END
RETURN @S
END

SELECT DBO.PRINTNUM(20)

