CREATE OR ALTER FUNCTION MAXOFTHREE(@NUM1 INT , @NUM2 INT , @NUM3 INT)
RETURNS VARCHAR(500)
AS
BEGIN
DECLARE @MAX INT
IF @NUM1 > @NUM2 AND @NUM1 > @NUM3
SET @MAX = @NUM1

ELSE IF @NUM2 > @NUM1 AND @NUM2 > @NUM3
SET @MAX = @NUM2

ELSE IF @NUM3 > @NUM1 AND @NUM3 > @NUM2
SET @MAX = @NUM3

RETURN 'MAXIMUM NUMBER IS' + ' ' + CAST(@MAX AS varchar)

END

SELECT DBO.MAXOFTHREE(20 , 30 , 50)

