CREATE FUNCTION PRINTFACTORIAL(@N INT)
RETURNS INT
AS
BEGIN
DECLARE @S INT
SET @S = 1
WHILE(@N>0)
BEGIN
SET @S = @S*@N
SET @N = @N - 1
END
RETURN @S
END

