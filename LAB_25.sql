CREATE OR ALTER FUNCTION CALSQUAREANDQUBE(@N INT)
RETURNS VARCHAR(500)
AS
BEGIN
DECLARE @SQ INT , @CU INT 
SET @SQ = @N*@N
SET @CU = @N*@N*@N

RETURN 'SQUARE AND QUBE OF THE NUMBER IS' + ' ' + CAST(@SQ  AS varchar) + ' ' + CAST(@CU AS VARCHAR)

END


