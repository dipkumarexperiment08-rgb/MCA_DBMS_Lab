 CREATE TRIGGER LOG_INSERT_OPERATIONS
 ON EMPLOYEE
 INSTEAD OF INSERT
AS
BEGIN
DECLARE @EID INT
	SELECT @EID = EID  FROM INSERTED
	INSERT INTO EMPLOYEE_LOG VALUES(@EID, NULL , NULL , NULL , 'INSERT' , GETDATE())
END

--

ALTER TRIGGER LOG_DELETE_OPERATIONS
ON EMPLOYEE
INSTEAD OF DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO EMPLOYEE_LOG
    VALUES (
        (SELECT EID FROM DELETED),
        NULL,
        NULL,
        NULL,
        'DELETE',
        GETDATE()
    );

    DELETE FROM EMPLOYEE
    WHERE EID IN (SELECT EID FROM DELETED);
END;


