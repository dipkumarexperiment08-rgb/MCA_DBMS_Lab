CREATE PROC SALARY_STATICSTICS
AS
BEGIN
SELECT DEPARTMENT ,SUM(SALARY) AS [TOTAL SALARY] ,  MAX(SALARY) AS [MAXIMUM SALARY] , MIN(SALARY) AS [MINIMUM SALARY], AVG(SALARY) AS [AVERAGE SALARY]FROM EMPLOYEE
GROUP BY DEPARTMENT
END

EXEC SALARY_STATICSTICS


