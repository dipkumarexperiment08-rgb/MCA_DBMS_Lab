--5)Create a stored procedure to display top N highest paid employees from each department (Value of N 
--is entered by user). 

ALTER PROC HIGHEST_PAID_TO_N_EMPLOYEE
@N INT
AS
BEGIN
WITH CTE AS (
SELECT * , DENSE_RANK() OVER (PARTITION BY DEPARTMENT ORDER BY SALARY DESC ) AS TOP_NUM
FROM EMPLOYEE)
SELECT * FROM CTE 
WHERE TOP_NUM<=@N
END
EXEC HIGHEST_PAID_TO_N_EMPLOYEE 1


