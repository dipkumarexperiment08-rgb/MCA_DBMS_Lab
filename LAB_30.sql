CREATE PROCEDURE CHECK_SALARY
@EID INT,
@SALARY INT
AS
BEGIN
	IF @SALARY <= 0
		THROW 50002, 'THIS SALARY IS IN NEGATIVE OR ZERO',1
	ELSE
		UPDATE EMPLOYEE
		SET SALARY = @SALARY
		WHERE EID = @EID
END

