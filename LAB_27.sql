DECLARE @EID INT
DECLARE @FNAME VARCHAR(50)
DECLARE @LNAME VARCHAR(50)
DECLARE @DEPARTMENTNAME VARCHAR(50)
DECLARE @SALARY DECIMAL
DECLARE @CITY VARCHAR(50)
DECLARE @GENDER VARCHAR(50)
DECLARE @JOINIYEAR DATE
DECLARE Employee_Cursor CURSOR
FOR
SELECT FIRSTNAME , LASTNAME , DEPARTMENT , SALARY , CITY , GENDER , JOININGYEAR FROM EMPLOYEE
OPEN Employee_Cursor 
FETCH NEXT FROM Employee_Cursor INTO @FNAME,@LNAME,@DEPARTMENTNAME,@SALARY,@CITY,@GENDER,@JOINIYEAR
WHILE @@FETCH_STATUS = 0
BEGIN
PRINT @FNAME+' '+@LNAME
FETCH NEXT FROM  Employee_Cursor INTO @FNAME,@LNAME,@DEPARTMENTNAME,@SALARY,@CITY,@GENDER,@JOINIYEAR
END
CLOSE Employee_Cursor
DEALLOCATE Employee_Cursor

