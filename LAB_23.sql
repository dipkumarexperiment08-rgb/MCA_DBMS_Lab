CREATE PROC DISPLAY_DEPARTMENT_WISE_SALARY
AS
BEGIN
SELECT DEPARTMENT , MAX(SALARY) AS [MAXIMUM SALARY] , MIN(SALARY) AS [MINIMUM SALARY], AVG(SALARY) AS [AVERAGE SALARY]FROM EMPLOYEE
GROUP BY DEPARTMENT
END

EXEC DISPLAY_DEPARTMENT_WISE_SALARY

--10)
CREATE PROC DISPLAY_DEPARTMENT_WISE_TOTAL_SALARY
@DEPT VARCHAR(50)
AS
BEGIN
SELECT DEPARTMENT , SUM(SALARY) [TOTAL SALARY OF DEPARTMENT] FROM EMPLOYEE
WHERE DEPARTMENT = @DEPT
GROUP BY DEPARTMENT
END

EXEC DISPLAY_DEPARTMENT_WISE_TOTAL_SALARY 'IT'