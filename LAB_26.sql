CREATE OR ALTER FUNCTION STUDENT_BRANCH(@BRANCH VARCHAR(50))
RETURNS TABLE
AS
RETURN(
SELECT COUNT(STDID) AS [STUDENT_COUNT] FROM STUDENT 
WHERE BRANCH = @BRANCH
GROUP BY BRANCH
)

SELECT * FROM STUDENT_BRANCH('COMPUTER')


